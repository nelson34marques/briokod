/** Retorna o ícone do módulo correspondente pelo ID ou tipo */
export function getModuleIcon(moduleId, size = 16, className = '') {
  switch (moduleId) {
    case 'm1':
      return <IconZap size={size} className={className} />;
    case 'm2':
      return <IconTarget size={size} className={className} />;
    case 'm3':
      return <IconRepeat size={size} className={className} />;
    case 'm4':
      return <IconPackage size={size} className={className} />;
    case 'm5':
      return <IconTrophy size={size} className={className} />;
    default:
      return <IconZap size={size} className={className} />;
  }
}
